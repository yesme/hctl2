#!/usr/bin/env bash
# Exercise the compressor used by both packaging actions, not PATH's zstd.
set -euo pipefail

: "${PACKAGING_HELPERS:?Buck must provide packaging helpers}"
# shellcheck source=../../packaging/dependencies/common/action.sh
source "$PACKAGING_HELPERS/common/action.sh"
require_pinned_zstd

work="$(mktemp -d "${TMPDIR:-/tmp}/hctl2-zstd-test.XXXXXX")"
trap 'find "${work:?}" -depth -delete' EXIT
dd if=/dev/urandom of="$work/input" bs=1048576 count=3 2>/dev/null
compress_archive <"$work/input" >"$work/normal.zst"
run_zstd -dc "$work/normal.zst" >"$work/output"
cmp "$work/input" "$work/output"

# A poisonous user configuration and a different PATH compressor cannot alter
# the bytes generated by the declared tool: ZSTD_CLEVEL and ZSTD_NBTHREADS are
# cleared, and the pinned binary is called by absolute path.
mkdir "$work/bin"
printf '#!/bin/sh\nexit 99\n' >"$work/bin/zstd"
chmod +x "$work/bin/zstd"
PATH="$work/bin:$PATH" ZSTD_CLEVEL=1 ZSTD_NBTHREADS=1 \
    compress_archive <"$work/input" >"$work/poisoned.zst"
cmp "$work/normal.zst" "$work/poisoned.zst"

# The worker count never changes the stream, but the fixture has to cross job
# boundaries for the assertion to mean anything. In long-distance mode the job
# log is MAX(21, cycleLog(chainLog, strategy) + 3) (lib/compress/zstdmt_compress.c,
# ZSTDMT_computeTargetJobLog), so the shipped `-22 --long=27` runs 512 MiB jobs
# on our archives — one job, where this property holds by construction and
# cannot be observed. `-3 --long=21` runs 2 MiB jobs, and 16 MiB of text really
# does span several of them.
awk 'BEGIN { for (i = 0; i < 260000; i++) print "hctl2 worker invariance line " i " with some text to compress" }' >"$work/split-text"
run_zstd -3 --long=21 -T1 -c "$work/split-text" >"$work/split-one.zst"
run_zstd -3 --long=21 -T3 -c "$work/split-text" >"$work/split-three.zst"
cmp "$work/split-one.zst" "$work/split-three.zst"
# The single-threaded encoder is a different code path in the same build, so a
# difference here only shows the fixture is not a no-op — it is not evidence
# that the jobs above were split.
run_zstd -3 --long=21 --single-thread -c "$work/split-text" >"$work/split-single.zst"
if cmp -s "$work/split-one.zst" "$work/split-single.zst"; then
    die "the split fixture does not distinguish the encoder paths at all"
fi

# Presets: the default is the shipped --ultra -22 stream byte for byte; `fast`
# (-12) still round-trips; anything else is rejected instead of silently
# falling back.
run_zstd --ultra -22 --long=27 -T0 -c <"$work/input" >"$work/explicit-22.zst"
cmp "$work/normal.zst" "$work/explicit-22.zst"
HCTL2_ZSTD_PRESET=release compress_archive <"$work/input" >"$work/release.zst"
cmp "$work/normal.zst" "$work/release.zst"
awk 'BEGIN { for (i = 0; i < 131072; i++) print "hctl2 preset regression line" }' >"$work/text"
run_zstd -12 -T0 -c <"$work/text" >"$work/text-12.zst"
HCTL2_ZSTD_PRESET=fast compress_archive <"$work/text" >"$work/text-fast.zst"
cmp "$work/text-12.zst" "$work/text-fast.zst"
run_zstd --ultra -22 --long=27 -T0 -c <"$work/text" >"$work/text-22.zst"
compress_archive <"$work/text" >"$work/text-default.zst"
cmp "$work/text-22.zst" "$work/text-default.zst"
# On compressible data -12 and -22 produce different streams, so this catches
# `fast` silently reverting to the release preset.
if cmp -s "$work/text-12.zst" "$work/text-22.zst"; then
    die "compressible fixture does not distinguish -12 from -22"
fi
if (HCTL2_ZSTD_PRESET=bogus compress_archive <"$work/input" >/dev/null) >"$work/bogus-preset.log" 2>&1; then
    die "unknown zstd preset was accepted"
fi
grep -F 'unsupported HCTL2_ZSTD_PRESET' "$work/bogus-preset.log" >/dev/null
if (HCTL2_ZSTD_PRESET= compress_archive <"$work/input" >/dev/null) >"$work/empty-preset.log" 2>&1; then
    die "empty zstd preset was accepted as the default"
fi
grep -F 'unsupported HCTL2_ZSTD_PRESET' "$work/empty-preset.log" >/dev/null

dd if="$work/normal.zst" of="$work/broken.zst" bs=1 count=16 2>/dev/null
if run_zstd -t "$work/broken.zst" 2>/dev/null; then
    die "truncated zstd stream was accepted"
fi
if (HCTL2_ZSTD_VERSION=0.0.0 require_pinned_zstd) >"$work/wrong-version.log" 2>&1; then
    die "unexpected zstd version was accepted"
fi
grep -F 'zstd version mismatch' "$work/wrong-version.log" >/dev/null
if (HCTL2_ZSTD_ROOT="$work/missing" require_pinned_zstd) >"$work/missing-tool.log" 2>&1; then
    die "missing pinned tool fell back to PATH"
fi
grep -F 'could not run pinned zstd' "$work/missing-tool.log" >/dev/null
printf 'zstd pin, environment isolation, presets, round trip, worker-count reproducibility and rejection tests passed\n'
